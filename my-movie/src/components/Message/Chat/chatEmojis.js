const emojiById = new Map(CHAT_EMOJIS.map((item) => [item.id, item]));

const notoFile = (id, file) => `https://fonts.gstatic.com/s/e/notoemoji/latest/${id}/${file}`;

export const emojiStill = (id) => notoFile(id, 'emoji.svg');

export const emojiMotion = (id) => notoFile(id, '512.webp');

export const emojiMatches = (emoji, query) => {
  const needle = String(query || '').trim().toLowerCase().replace(/[ʻ’']/g, '');
  if (!needle) return true;
  return `${emoji.char} ${emoji.q}`.toLowerCase().replace(/[ʻ’']/g, '').includes(needle);
};

export const readRecentEmojiIds = () => {
  try {
    const raw = JSON.parse(window.localStorage.getItem(RECENT_KEY) || '[]');
    if (!Array.isArray(raw)) return [];
    return raw.filter((id) => typeof id === 'string' && emojiById.has(id)).slice(0, RECENT_MAX);
  } catch (_err) {
    return [];
  }
};

export const rememberEmoji = (id) => {
  const next = [id, ...readRecentEmojiIds().filter((item) => item !== id)].slice(0, RECENT_MAX);
  window.localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  return next;
};

export const emojiFromId = (id) => emojiById.get(id) || null;

const emojiPiece = (part) => {
  if (/^\s+$/.test(part)) return 'space';
  if (/^[#*0-9]\uFE0F\u20E3$/.test(part)) return 'emoji';
  if (/^\p{Regional_Indicator}{2}$/u.test(part)) return 'emoji';
  const core = part.replace(/[\uFE0F\u200D]/g, '').replace(/\p{Emoji_Modifier}/gu, '');
  if (!core || /[0-9#*]/.test(core)) return 'text';
  if (/^[\p{Extended_Pictographic}\p{Regional_Indicator}]+$/u.test(core)) return 'emoji';
  return 'text';
};

export const emojiOnlyCount = (value) => {
  const text = String(value || '').trim();
  if (!text) return 0;
  const parts = typeof Intl !== 'undefined' && Intl.Segmenter
    ? [...new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(text)].map((item) => item.segment)
    : [...text];
  let count = 0;
  for (const part of parts) {
    const kind = emojiPiece(part);
    if (kind === 'space') continue;
    if (kind !== 'emoji') return 0;
    count += 1;
  }
  return count;
};
